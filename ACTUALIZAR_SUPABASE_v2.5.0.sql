-- Aceptación atómica: impide que dos conductores tomen el mismo viaje.
create or replace function public.accept_ride_atomic(
  p_ride_id text,
  p_driver_id text,
  p_driver_name text,
  p_driver_photo text default null,
  p_driver_rating numeric default 5,
  p_driver_lat double precision default null,
  p_driver_lng double precision default null
)
returns public.rides
language plpgsql
security definer
set search_path=public
as $$
declare
  v_ride public.rides;
begin
  update public.rides
  set status='accepted',
      driver_id=p_driver_id,
      driver_name=p_driver_name,
      driver_photo=p_driver_photo,
      driver_rating=coalesce(p_driver_rating,5),
      driver_lat=p_driver_lat,
      driver_lng=p_driver_lng,
      accepted_at=now(),
      driver_last_update_at=now(),
      offered_driver_id=null,offered_at=null,offer_expires_at=null,
      last_event_at=now(),
      updated_at=now()
  where id::text=p_ride_id and status='searching'
    and (offered_driver_id is null or offered_driver_id=p_driver_id or offer_expires_at<now())
    and exists(select 1 from public.profiles p where p.device_id=p_driver_id and p.role='driver' and p.status='active' and p.approval_status='approved' and coalesce(p.is_online,false)=true)
    and not exists(select 1 from public.rides busy where busy.driver_id=p_driver_id and busy.status in ('accepted','arrived','in_progress') and busy.id::text<>p_ride_id)
  returning * into v_ride;

  if not found then
    raise exception using errcode='P0001', message='RIDE_UNAVAILABLE';
  end if;

  insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
  values(p_ride_id,'accepted','driver',p_driver_id,jsonb_build_object('driver_name',p_driver_name));
  return v_ride;
end;
$$;

grant execute on function public.accept_ride_atomic(text,text,text,text,numeric,double precision,double precision) to anon,authenticated;

-- Registro automático de cada cambio de estado.
create or replace function public.audit_ride_status_change()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if tg_op='INSERT' then
    insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
    values(new.id::text,'created','passenger',new.passenger_id,jsonb_build_object('status',new.status));
  elsif old.status is distinct from new.status then
    new.last_event_at=now();
    insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
    values(new.id::text,'status_changed',coalesce(new.canceled_by,case when new.driver_id is not null then 'driver' else 'system' end),coalesce(new.driver_id,new.passenger_id),jsonb_build_object('from',old.status,'to',new.status));
  end if;
  if tg_op='INSERT' then new.last_event_at=coalesce(new.last_event_at,now());end if;
  return new;
end;
$$;

drop trigger if exists rides_audit_status on public.rides;
create trigger rides_audit_status before insert or update on public.rides for each row execute function public.audit_ride_status_change();

