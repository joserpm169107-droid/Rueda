-- En la creación se ofrece primero al conductor aprobado y conectado más cercano.
create or replace function public.assign_initial_driver_offer()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare v_driver text;
begin
  if new.status='searching' and new.offered_driver_id is null and new.pickup_lat is not null and new.pickup_lng is not null then
    select p.device_id into v_driver
    from public.profiles p
    where p.role='driver' and p.status='active' and p.approval_status='approved'
      and coalesce(p.is_online,false)=true and p.last_lat is not null and p.last_lng is not null
      and (p.last_seen_at is null or p.last_seen_at>now()-interval '2 minutes')
      and (new.vehicle_type is null or p.vehicle_type is null or p.vehicle_type=new.vehicle_type)
      and not exists(select 1 from public.rides busy where busy.driver_id=p.device_id and busy.status in ('accepted','arrived','in_progress'))
    order by power(p.last_lat-new.pickup_lat,2)+power(p.last_lng-new.pickup_lng,2)
    limit 1;
    if v_driver is not null then new.offered_driver_id=v_driver;new.offered_at=now();new.offer_expires_at=now()+interval '35 seconds';end if;
  end if;
  return new;
end;
$$;
drop trigger if exists rides_assign_initial_offer on public.rides;
create trigger rides_assign_initial_offer before insert on public.rides for each row execute function public.assign_initial_driver_offer();

-- Un conductor libre reclama atómicamente la solicitud disponible más cercana.
create or replace function public.claim_nearest_ride_offer(p_driver_id text,p_driver_lat double precision,p_driver_lng double precision,p_vehicle_type text default null)
returns public.rides
language plpgsql
security definer
set search_path=public
as $$
declare v_id text;v_ride public.rides;
begin
  if not exists(
    select 1 from public.profiles p
    where p.device_id=p_driver_id and p.role='driver' and p.status='active'
      and p.approval_status='approved' and coalesce(p.is_online,false)=true
  ) then return null; end if;
  if exists(select 1 from public.rides busy where busy.driver_id=p_driver_id and busy.status in ('accepted','arrived','in_progress')) then return null; end if;
  select r.id::text into v_id
  from public.rides r
  where r.status='searching'
    and (p_vehicle_type is null or r.vehicle_type is null or r.vehicle_type=p_vehicle_type)
    and (r.offered_driver_id=p_driver_id or r.offered_driver_id is null or r.offer_expires_at<now())
    and not exists(select 1 from public.ride_offer_attempts a where a.ride_id=r.id::text and a.driver_id=p_driver_id)
  order by case when r.pickup_lat is null or r.pickup_lng is null then 999999 else power(r.pickup_lat-p_driver_lat,2)+power(r.pickup_lng-p_driver_lng,2) end,r.created_at
  for update skip locked
  limit 1;
  if v_id is null then return null;end if;
  update public.rides set offered_driver_id=p_driver_id,offered_at=now(),offer_expires_at=now()+interval '35 seconds',updated_at=now() where id::text=v_id and status='searching' returning * into v_ride;
  return v_ride;
end;
$$;

-- Al rechazar o vencer la oferta, la pasa al siguiente conductor cercano.
create or replace function public.decline_ride_offer(p_ride_id text,p_driver_id text,p_outcome text default 'declined')
returns public.rides
language plpgsql
security definer
set search_path=public
as $$
declare v_ride public.rides;v_next text;
begin
  insert into public.ride_offer_attempts(ride_id,driver_id,outcome) values(p_ride_id,p_driver_id,coalesce(p_outcome,'declined'));
  select * into v_ride from public.rides where id::text=p_ride_id and status='searching' and (offered_driver_id is null or offered_driver_id=p_driver_id or offer_expires_at<now()) for update;
  if not found then return null;end if;
  select p.device_id into v_next from public.profiles p
  where p.role='driver' and p.status='active' and p.approval_status='approved' and coalesce(p.is_online,false)=true
    and p.last_lat is not null and p.last_lng is not null and p.device_id<>p_driver_id
    and (p.last_seen_at is null or p.last_seen_at>now()-interval '2 minutes')
    and (v_ride.vehicle_type is null or p.vehicle_type is null or p.vehicle_type=v_ride.vehicle_type)
    and not exists(select 1 from public.ride_offer_attempts a where a.ride_id=p_ride_id and a.driver_id=p.device_id)
    and not exists(select 1 from public.rides busy where busy.driver_id=p.device_id and busy.status in ('accepted','arrived','in_progress'))
  order by case when v_ride.pickup_lat is null or v_ride.pickup_lng is null then 999999 else power(p.last_lat-v_ride.pickup_lat,2)+power(p.last_lng-v_ride.pickup_lng,2) end
  limit 1;
  update public.rides set offered_driver_id=v_next,offered_at=case when v_next is null then null else now() end,offer_expires_at=case when v_next is null then null else now()+interval '35 seconds' end,updated_at=now() where id::text=p_ride_id returning * into v_ride;
  return v_ride;
end;
$$;

