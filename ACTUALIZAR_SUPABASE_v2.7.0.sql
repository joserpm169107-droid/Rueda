-- Eliminación definitiva tolerante a diferencias de esquema entre versiones anteriores.
create or replace function public.admin_delete_person_permanently(
  p_person_id text,p_role text,p_reason text,p_admin_name text,p_admin_code text
)
returns jsonb
language plpgsql
security definer
set search_path=public,storage
as $$
declare
  v_profile public.profiles;
  v_keys text[];
  v_ride_ids text[]:=array[]::text[];
  v_rides_count integer:=0;
  v_media_count integer:=0;
  v_sql text;
begin
  if p_admin_code is distinct from 'RUEDA2026' then raise exception using errcode='P0001',message='ADMIN_CODE_INVALID'; end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='DELETE_REASON_REQUIRED'; end if;
  if p_role not in ('driver','passenger') then raise exception using errcode='P0001',message='ROLE_INVALID'; end if;

  select * into v_profile from public.profiles p
  where p.role=p_role and (p.device_id=p_person_id or p.id::text=p_person_id)
  limit 1 for update;
  if not found then raise exception using errcode='P0001',message='PROFILE_NOT_FOUND'; end if;

  v_keys:=array_remove(array[p_person_id,v_profile.id::text,v_profile.device_id],null);
  select coalesce(array_agg(id::text),array[]::text[]) into v_ride_ids
  from public.rides
  where (p_role='driver' and driver_id=any(v_keys)) or (p_role='passenger' and passenger_id=any(v_keys));
  v_rides_count:=coalesce(array_length(v_ride_ids,1),0);

  if to_regclass('public.driver_reports') is not null then
    v_sql:='delete from public.driver_reports where false';
    if exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='ride_id') then
      v_sql:=v_sql||' or ride_id::text=any($1)';
    end if;
    if p_role='driver' and exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='driver_id') then
      v_sql:=v_sql||' or driver_id::text=any($2)';
    end if;
    if p_role='passenger' and exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='passenger_id') then
      v_sql:=v_sql||' or passenger_id::text=any($2)';
    end if;
    execute v_sql using v_ride_ids,v_keys;
  end if;

  if to_regclass('public.ride_events') is not null then execute 'delete from public.ride_events where ride_id::text=any($1)' using v_ride_ids; end if;
  if to_regclass('public.ride_offer_attempts') is not null then execute 'delete from public.ride_offer_attempts where ride_id::text=any($1) or driver_id::text=any($2)' using v_ride_ids,v_keys; end if;
  if to_regclass('public.ride_messages') is not null then execute 'delete from public.ride_messages where ride_id::text=any($1) or sender_id::text=any($2)' using v_ride_ids,v_keys; end if;

  if to_regclass('public.support_cases') is not null then
    delete from public.support_cases where created_by_id=any(v_keys) or related_ride_id=any(v_ride_ids);
  end if;

  delete from public.rides where id::text=any(v_ride_ids);

  begin
    with deleted as (
      delete from storage.objects
      where bucket_id='sobre-ruedas-media' and (
        name like '%/'||coalesce(v_profile.device_id,'__none__')||'/%' or
        name like '%/'||v_profile.id::text||'/%'
      ) returning 1
    ) select count(*) into v_media_count from deleted;
  exception when others then
    v_media_count:=0;
  end;

  delete from public.profiles where id=v_profile.id;

  begin
    execute 'delete from public.admin_action_log where target_id::text=any($1)' using v_keys;
    insert into public.admin_action_log(action,target_id,target_role,reason,admin_name,metadata,created_at)
    values('permanent_delete_'||p_role,'[eliminado]',p_role,trim(p_reason),p_admin_name,
      jsonb_build_object('rides_deleted',v_rides_count,'media_deleted',v_media_count),now());
  exception when others then null;
  end;

  return jsonb_build_object('ok',true,'role',p_role,'rides_deleted',v_rides_count,'media_deleted',v_media_count);
end;
$$;

-- Mensajería del viaje. La interfaz solo la habilita para participantes del viaje.
create or replace function public.send_ride_message(
  p_ride_id text,p_sender_id text,p_sender_role text,p_message text,p_message_type text default 'text'
)
returns public.ride_messages
language plpgsql
security definer
set search_path=public
as $$
declare v_ride public.rides;v_message public.ride_messages;
begin
  if p_sender_role not in ('passenger','driver') then raise exception using errcode='P0001',message='MESSAGE_ROLE_INVALID'; end if;
  if nullif(trim(coalesce(p_message,'')),'') is null then raise exception using errcode='P0001',message='MESSAGE_EMPTY'; end if;
  if length(p_message)>800 then raise exception using errcode='P0001',message='MESSAGE_TOO_LONG'; end if;
  select * into v_ride from public.rides where id::text=p_ride_id;
  if not found then raise exception using errcode='P0001',message='RIDE_NOT_FOUND'; end if;
  if not ((p_sender_role='passenger' and v_ride.passenger_id=p_sender_id) or (p_sender_role='driver' and v_ride.driver_id=p_sender_id)) then
    raise exception using errcode='P0001',message='MESSAGE_SENDER_NOT_PARTICIPANT';
  end if;
  if v_ride.status not in ('searching','accepted','arrived','in_progress') and coalesce(v_ride.finished_at,v_ride.canceled_at,v_ride.updated_at)<now()-interval '30 minutes' then
    raise exception using errcode='P0001',message='CHAT_CLOSED';
  end if;
  insert into public.ride_messages(ride_id,sender_id,sender_role,message,message_type)
  values(p_ride_id,p_sender_id,p_sender_role,trim(p_message),coalesce(nullif(p_message_type,''),'text'))
  returning * into v_message;
  return v_message;
end;
$$;

create or replace function public.mark_ride_messages_read(
  p_ride_id text,p_reader_id text,p_reader_role text
)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare v_count integer;v_ride public.rides;
begin
  select * into v_ride from public.rides where id::text=p_ride_id;
  if not found then return 0; end if;
  if not ((p_reader_role='passenger' and v_ride.passenger_id=p_reader_id) or (p_reader_role='driver' and v_ride.driver_id=p_reader_id)) then
    raise exception using errcode='P0001',message='MESSAGE_READER_NOT_PARTICIPANT';
  end if;
  update public.ride_messages set read_at=coalesce(read_at,now())
  where ride_id=p_ride_id and sender_id<>p_reader_id and read_at is null;
  get diagnostics v_count=row_count;
  return v_count;
end;
$$;

create or replace function public.create_support_case(
  p_creator_id text,p_creator_role text,p_ride_id text,p_category text,p_subject text,p_description text,p_priority text default 'normal'
)
returns public.support_cases
language plpgsql
security definer
set search_path=public
as $$
declare v_case public.support_cases;
begin
  if p_creator_role not in ('passenger','driver') then raise exception using errcode='P0001',message='SUPPORT_ROLE_INVALID'; end if;
  if nullif(trim(coalesce(p_category,'')),'') is null or nullif(trim(coalesce(p_description,'')),'') is null then
    raise exception using errcode='P0001',message='SUPPORT_DETAILS_REQUIRED';
  end if;
  insert into public.support_cases(created_by_id,created_by_role,related_ride_id,category,subject,description,priority)
  values(p_creator_id,p_creator_role,nullif(p_ride_id,''),trim(p_category),coalesce(nullif(trim(p_subject),''),trim(p_category)),trim(p_description),
    case when p_priority in ('normal','high','emergency') then p_priority else 'normal' end)
  returning * into v_case;
  if p_ride_id is not null and p_ride_id<>'' then update public.rides set support_flag=true,updated_at=now() where id::text=p_ride_id; end if;
  insert into public.support_messages(case_id,sender_id,sender_role,message)
  values(v_case.id,p_creator_id,p_creator_role,trim(p_description));
  return v_case;
end;
$$;


create or replace function public.send_support_message(
  p_case_id uuid,p_sender_id text,p_sender_role text,p_message text
)
returns public.support_messages
language plpgsql
security definer
set search_path=public
as $$
declare v_case public.support_cases;v_message public.support_messages;
begin
  if p_sender_role not in ('passenger','driver') then raise exception using errcode='P0001',message='SUPPORT_ROLE_INVALID'; end if;
  if nullif(trim(coalesce(p_message,'')),'') is null then raise exception using errcode='P0001',message='SUPPORT_MESSAGE_EMPTY'; end if;
  if length(p_message)>1800 then raise exception using errcode='P0001',message='SUPPORT_MESSAGE_TOO_LONG'; end if;
  select * into v_case from public.support_cases where id=p_case_id for update;
  if not found then raise exception using errcode='P0001',message='SUPPORT_CASE_NOT_FOUND'; end if;
  if v_case.created_by_id<>p_sender_id or v_case.created_by_role<>p_sender_role then
    raise exception using errcode='P0001',message='SUPPORT_SENDER_NOT_OWNER';
  end if;
  if v_case.status in ('resolved','closed') then raise exception using errcode='P0001',message='SUPPORT_CASE_CLOSED'; end if;
  insert into public.support_messages(case_id,sender_id,sender_role,message)
  values(p_case_id,p_sender_id,p_sender_role,trim(p_message)) returning * into v_message;
  update public.support_cases set status=case when status='open' then 'in_review' else status end,updated_at=now() where id=p_case_id;
  return v_message;
end;
$$;

