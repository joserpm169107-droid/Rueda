-- Regla central: una cuenta suspendida nunca puede permanecer en línea.
create or replace function public.enforce_profile_operability()
returns trigger
language plpgsql
set search_path=public
as $$
begin
  if new.suspended_until is not null and new.suspended_until>now() then
    new.is_online:=false;
  end if;
  if new.approval_status in ('deleted','rejected') or new.status in ('deleted','blocked') then
    new.is_online:=false;
  end if;
  return new;
end;
$$;
drop trigger if exists profiles_enforce_operability on public.profiles;
create trigger profiles_enforce_operability before insert or update on public.profiles
for each row execute function public.enforce_profile_operability();

update public.profiles
set is_online=false,updated_at=now()
where (suspended_until is not null and suspended_until>now())
   or approval_status in ('deleted','rejected')
   or status in ('deleted','blocked');

-- Ofertas iniciales: excluye conductores suspendidos o bloqueados.
create or replace function public.assign_initial_driver_offer()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare v_driver text;
begin
  if new.status='searching' and new.offered_driver_id is null and new.pickup_lat is not null and new.pickup_lng is not null then
    select p.device_id into v_driver
    from public.profiles p
    where p.role='driver'
      and p.status='active'
      and p.approval_status='approved'
      and (p.suspended_until is null or p.suspended_until<=now())
      and coalesce(p.is_online,false)=true
      and p.last_lat is not null and p.last_lng is not null
      and (p.last_seen_at is null or p.last_seen_at>now()-interval '2 minutes')
      and (new.vehicle_type is null or p.vehicle_type is null or p.vehicle_type=new.vehicle_type)
      and not exists(select 1 from public.rides busy where busy.driver_id=p.device_id and busy.status in ('accepted','arrived','in_progress'))
    order by power(p.last_lat-new.pickup_lat,2)+power(p.last_lng-new.pickup_lng,2)
    limit 1;
    if v_driver is not null then
      new.offered_driver_id:=v_driver;
      new.offered_at:=now();
      new.offer_expires_at:=now()+interval '35 seconds';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists rides_assign_initial_offer on public.rides;
create trigger rides_assign_initial_offer before insert on public.rides
for each row execute function public.assign_initial_driver_offer();

create or replace function public.claim_nearest_ride_offer(
  p_driver_id text,
  p_driver_lat double precision,
  p_driver_lng double precision,
  p_vehicle_type text default null
)
returns public.rides
language plpgsql
security definer
set search_path=public
as $$
declare v_id text;v_ride public.rides;
begin
  if not exists(
    select 1 from public.profiles p
    where p.device_id=p_driver_id
      and p.role='driver'
      and p.status='active'
      and p.approval_status='approved'
      and (p.suspended_until is null or p.suspended_until<=now())
      and coalesce(p.is_online,false)=true
  ) then return null; end if;

  if exists(select 1 from public.rides busy where busy.driver_id=p_driver_id and busy.status in ('accepted','arrived','in_progress')) then
    return null;
  end if;

  select r.id::text into v_id
  from public.rides r
  where r.status='searching'
    and (p_vehicle_type is null or r.vehicle_type is null or r.vehicle_type=p_vehicle_type)
    and (r.offered_driver_id=p_driver_id or r.offered_driver_id is null or r.offer_expires_at<now())
    and not exists(select 1 from public.ride_offer_attempts a where a.ride_id=r.id::text and a.driver_id=p_driver_id)
  order by case when r.pickup_lat is null or r.pickup_lng is null then 999999 else power(r.pickup_lat-p_driver_lat,2)+power(r.pickup_lng-p_driver_lng,2) end,r.created_at
  for update skip locked
  limit 1;

  if v_id is null then return null; end if;
  update public.rides
  set offered_driver_id=p_driver_id,offered_at=now(),offer_expires_at=now()+interval '35 seconds',updated_at=now()
  where id::text=v_id and status='searching'
  returning * into v_ride;
  return v_ride;
end;
$$;

create or replace function public.accept_ride_atomic(
  p_ride_id text,
  p_driver_id text,
  p_driver_name text,
  p_driver_photo text default null,
  p_driver_rating numeric default 5,
  p_driver_lat double precision default null,
  p_driver_lng double precision default null
)
returns public.rides
language plpgsql
security definer
set search_path=public
as $$
declare v_ride public.rides;
begin
  update public.rides
  set status='accepted',driver_id=p_driver_id,driver_name=p_driver_name,
      driver_photo=p_driver_photo,driver_rating=coalesce(p_driver_rating,5),
      driver_lat=p_driver_lat,driver_lng=p_driver_lng,accepted_at=now(),
      driver_last_update_at=now(),offered_driver_id=null,offered_at=null,
      offer_expires_at=null,last_event_at=now(),updated_at=now()
  where id::text=p_ride_id and status='searching'
    and (offered_driver_id is null or offered_driver_id=p_driver_id or offer_expires_at<now())
    and exists(
      select 1 from public.profiles p
      where p.device_id=p_driver_id and p.role='driver' and p.status='active'
        and p.approval_status='approved'
        and (p.suspended_until is null or p.suspended_until<=now())
        and coalesce(p.is_online,false)=true
    )
    and not exists(
      select 1 from public.rides busy
      where busy.driver_id=p_driver_id and busy.status in ('accepted','arrived','in_progress') and busy.id::text<>p_ride_id
    )
  returning * into v_ride;

  if not found then
    raise exception using errcode='P0001',message='RIDE_UNAVAILABLE_OR_DRIVER_BLOCKED';
  end if;

  begin
    insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
    values(p_ride_id,'accepted','driver',p_driver_id,jsonb_build_object('driver_name',p_driver_name));
  exception when others then null;
  end;
  return v_ride;
end;
$$;

-- Administración atómica de viajes atascados.
create or replace function public.admin_resolve_ride(
  p_ride_id text,
  p_action text,
  p_reason text,
  p_admin_name text,
  p_admin_code text
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare v_ride public.rides;v_now timestamptz:=now();
begin
  if p_admin_code is distinct from 'RUEDA2026' then
    raise exception using errcode='P0001',message='ADMIN_CODE_INVALID';
  end if;
  if p_action not in ('finish','cancel') then
    raise exception using errcode='P0001',message='ADMIN_RIDE_ACTION_INVALID';
  end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then
    raise exception using errcode='P0001',message='ADMIN_RIDE_REASON_REQUIRED';
  end if;

  select * into v_ride from public.rides where id::text=p_ride_id for update;
  if not found then raise exception using errcode='P0001',message='RIDE_NOT_FOUND'; end if;

  if p_action='finish' then
    if v_ride.status not in ('accepted','arrived','in_progress') then
      raise exception using errcode='P0001',message='RIDE_CANNOT_BE_FINISHED_FROM_CURRENT_STATUS';
    end if;
    update public.rides
    set status='finished',finished_at=v_now,admin_finished_at=v_now,
        admin_finished_by=coalesce(nullif(trim(p_admin_name),''),'administración'),
        admin_note=trim(p_reason),offered_driver_id=null,offer_expires_at=null,
        last_event_at=v_now,updated_at=v_now
    where id::text=p_ride_id returning * into v_ride;
  else
    if v_ride.status not in ('searching','accepted','arrived','in_progress') then
      raise exception using errcode='P0001',message='RIDE_CANNOT_BE_CANCELED_FROM_CURRENT_STATUS';
    end if;
    update public.rides
    set status='canceled',canceled_at=v_now,canceled_by='admin',cancel_reason=trim(p_reason),
        admin_note=trim(p_reason),offered_driver_id=null,offered_at=null,offer_expires_at=null,
        last_event_at=v_now,updated_at=v_now
    where id::text=p_ride_id returning * into v_ride;
  end if;

  begin
    insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
    values(p_ride_id,'admin_'||p_action,'admin',p_admin_name,jsonb_build_object('reason',trim(p_reason),'status',v_ride.status));
  exception when undefined_table or undefined_column then null;
  end;
  begin
    insert into public.admin_action_log(action,target_id,target_role,reason,admin_name,metadata,created_at)
    values('admin_'||p_action||'_ride',p_ride_id,'ride',trim(p_reason),p_admin_name,jsonb_build_object('final_status',v_ride.status),v_now);
  exception when undefined_table or undefined_column then null;
  end;

  return jsonb_build_object('ok',true,'ride_id',p_ride_id,'status',v_ride.status);
end;
$$;

-- Suspensión robusta de pasajero o conductor.
create or replace function public.admin_suspend_profile(
  p_person_id text,p_role text,p_until timestamptz,p_reason text,p_admin_name text,p_admin_code text
)
returns public.profiles
language plpgsql
security definer
set search_path=public
as $$
declare v_profile public.profiles;
begin
  if p_admin_code is distinct from 'RUEDA2026' then raise exception using errcode='P0001',message='ADMIN_CODE_INVALID'; end if;
  if p_until is null or p_until<=now() then raise exception using errcode='P0001',message='SUSPENSION_DATE_INVALID'; end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='SUSPENSION_REASON_REQUIRED'; end if;

  select * into v_profile from public.profiles p
  where p.role=p_role and (p.device_id=p_person_id or p.id::text=p_person_id)
  limit 1 for update;
  if not found then raise exception using errcode='P0001',message='PROFILE_NOT_FOUND'; end if;

  update public.profiles set suspended_until=p_until,suspension_reason=trim(p_reason),suspended_at=now(),
    suspended_by=coalesce(nullif(trim(p_admin_name),''),'administración'),is_online=false,updated_at=now()
  where id=v_profile.id returning * into v_profile;

  update public.rides
  set status='canceled',canceled_at=now(),canceled_by='admin',cancel_reason='Cuenta suspendida: '||trim(p_reason),
      admin_note='Suspensión administrativa hasta '||p_until::text,offered_driver_id=null,offered_at=null,offer_expires_at=null,
      updated_at=now(),last_event_at=now()
  where status in ('searching','accepted','arrived','in_progress') and (
    (p_role='driver' and driver_id in (coalesce(v_profile.device_id,''),v_profile.id::text,p_person_id)) or
    (p_role='passenger' and passenger_id in (coalesce(v_profile.device_id,''),v_profile.id::text,p_person_id))
  );

  begin
    insert into public.admin_action_log(action,target_id,target_role,reason,admin_name,metadata,created_at)
    values('suspend_'||p_role,coalesce(v_profile.device_id,v_profile.id::text),p_role,trim(p_reason),p_admin_name,jsonb_build_object('suspended_until',p_until),now());
  exception when undefined_table or undefined_column then null;
  end;
  return v_profile;
end;
$$;

