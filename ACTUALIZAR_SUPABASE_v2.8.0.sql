-- Suspender, levantar suspensión, desactivar o reactivar una cuenta.
create or replace function public.admin_set_account_state_v280(
  p_person_id text,p_role text,p_action text,p_until timestamptz,p_reason text,p_admin_name text,p_admin_code text
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_profile public.profiles;
  v_keys text[];
  v_now timestamptz:=now();
  v_canceled integer:=0;
begin
  if p_admin_code is distinct from 'RUEDA2026' then raise exception using errcode='P0001',message='ADMIN_CODE_INVALID'; end if;
  if p_role not in ('driver','passenger') then raise exception using errcode='P0001',message='ROLE_INVALID'; end if;
  if p_action not in ('suspend','unsuspend','deactivate','reactivate') then raise exception using errcode='P0001',message='ACCOUNT_ACTION_INVALID'; end if;
  select * into v_profile from public.profiles p
  where p.role=p_role and (p.device_id=p_person_id or p.id::text=p_person_id)
  order by p.updated_at desc nulls last limit 1 for update;
  if not found then raise exception using errcode='P0001',message='PROFILE_NOT_FOUND'; end if;
  select array_agg(distinct x) into v_keys from unnest(array[p_person_id,v_profile.device_id,v_profile.id::text]) x where x is not null and x<>'';

  if p_action='suspend' then
    if p_until is null or p_until<=v_now then raise exception using errcode='P0001',message='SUSPENSION_DATE_INVALID'; end if;
    if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='SUSPENSION_REASON_REQUIRED'; end if;
    update public.profiles set suspended_until=p_until,suspension_reason=trim(p_reason),suspended_at=v_now,
      suspended_by=coalesce(nullif(trim(p_admin_name),''),'administración'),is_online=false,updated_at=v_now where id=v_profile.id;
    update public.rides set status='canceled',canceled_at=coalesce(canceled_at,v_now),canceled_by='admin',
      cancel_reason='Cuenta suspendida: '||trim(p_reason),admin_note='Suspensión administrativa',
      offered_driver_id=null,offered_at=null,offer_expires_at=null,last_event_at=v_now,updated_at=v_now
    where status in ('searching','accepted','arrived','in_progress')
      and ((p_role='driver' and driver_id::text=any(v_keys)) or (p_role='passenger' and passenger_id::text=any(v_keys)));
    get diagnostics v_canceled=row_count;
  elsif p_action='unsuspend' then
    update public.profiles set suspended_until=null,suspension_reason=null,suspended_at=null,suspended_by=null,is_online=false,updated_at=v_now where id=v_profile.id;
  elsif p_action='deactivate' then
    if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='DEACTIVATION_REASON_REQUIRED'; end if;
    update public.profiles set approval_status='rejected',is_online=false,deactivated_at=v_now,
      deactivated_by=coalesce(nullif(trim(p_admin_name),''),'administración'),deactivation_reason=trim(p_reason),updated_at=v_now where id=v_profile.id;
    update public.rides set status='canceled',canceled_at=coalesce(canceled_at,v_now),canceled_by='admin',
      cancel_reason='Cuenta desactivada: '||trim(p_reason),admin_note='Desactivación administrativa',
      offered_driver_id=null,offered_at=null,offer_expires_at=null,last_event_at=v_now,updated_at=v_now
    where status in ('searching','accepted','arrived','in_progress')
      and ((p_role='driver' and driver_id::text=any(v_keys)) or (p_role='passenger' and passenger_id::text=any(v_keys)));
    get diagnostics v_canceled=row_count;
  else
    update public.profiles set status='active',approval_status=case when p_role='driver' then 'pending' else 'approved' end,
      is_online=false,deactivated_at=null,deactivated_by=null,deactivation_reason=null,updated_at=v_now where id=v_profile.id;
  end if;

  begin
    insert into public.admin_action_log(action,target_id,target_role,reason,admin_name,metadata,created_at)
    values(p_action||'_'||p_role,coalesce(v_profile.device_id,p_person_id),p_role,nullif(trim(coalesce(p_reason,'')),''),p_admin_name,
      jsonb_build_object('until',p_until,'rides_canceled',v_canceled),v_now);
  exception when others then null;
  end;
  return jsonb_build_object('ok',true,'action',p_action,'role',p_role,'rides_canceled',v_canceled);
end;
$$;

-- Eliminación definitiva robusta. Conserva únicamente un identificador técnico/hash para impedir recreación automática.
create or replace function public.admin_delete_account_v280(
  p_person_id text,p_role text,p_reason text,p_admin_name text,p_admin_code text
)
returns jsonb language plpgsql security definer set search_path=public,storage as $$
declare
  v_profile public.profiles;
  v_keys text[];
  v_ride_ids text[]:=array[]::text[];
  v_rides_count integer:=0;
  v_media_count integer:=0;
  v_fk record;
  v_sql text;
begin
  if p_admin_code is distinct from 'RUEDA2026' then raise exception using errcode='P0001',message='ADMIN_CODE_INVALID'; end if;
  if p_role not in ('driver','passenger') then raise exception using errcode='P0001',message='ROLE_INVALID'; end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='DELETE_REASON_REQUIRED'; end if;

  select * into v_profile from public.profiles p
  where p.role=p_role and (p.device_id=p_person_id or p.id::text=p_person_id)
  order by p.updated_at desc nulls last limit 1 for update;
  if not found then
    if exists(select 1 from public.deleted_accounts d where d.role=p_role and d.device_id=p_person_id) then
      return jsonb_build_object('ok',true,'already_deleted',true,'rides_deleted',0,'media_deleted',0);
    end if;
    raise exception using errcode='P0001',message='PROFILE_NOT_FOUND';
  end if;
  select array_agg(distinct x) into v_keys from unnest(array[p_person_id,v_profile.device_id,v_profile.id::text]) x where x is not null and x<>'';

  insert into public.deleted_accounts(device_id,role,email_hash,phone_hash,reason,deleted_by,deleted_at)
  values(coalesce(v_profile.device_id,p_person_id),p_role,
    case when nullif(trim(coalesce(v_profile.email,'')),'') is null then null else public.sr_hash_contact_v280(v_profile.email) end,
    case when nullif(trim(coalesce(v_profile.phone,'')),'') is null then null else public.sr_hash_contact_v280(v_profile.phone) end,
    trim(p_reason),coalesce(nullif(trim(p_admin_name),''),'administración'),now())
  on conflict(device_id,role) do update set email_hash=excluded.email_hash,phone_hash=excluded.phone_hash,
    reason=excluded.reason,deleted_by=excluded.deleted_by,deleted_at=excluded.deleted_at;

  select coalesce(array_agg(r.id::text),array[]::text[]) into v_ride_ids from public.rides r
  where (p_role='driver' and r.driver_id::text=any(v_keys)) or (p_role='passenger' and r.passenger_id::text=any(v_keys));
  v_rides_count:=coalesce(array_length(v_ride_ids,1),0);

  begin delete from public.ride_messages where ride_id::text=any(v_ride_ids) or sender_id::text=any(v_keys); exception when others then null; end;
  begin delete from public.ride_events where ride_id::text=any(v_ride_ids) or actor_id::text=any(v_keys); exception when others then null; end;
  begin delete from public.ride_offer_attempts where ride_id::text=any(v_ride_ids) or driver_id::text=any(v_keys); exception when others then null; end;
  begin delete from public.support_cases where created_by_id::text=any(v_keys) or related_ride_id::text=any(v_ride_ids); exception when others then null; end;

  if to_regclass('public.driver_reports') is not null then
    v_sql:='delete from public.driver_reports where false';
    if exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='ride_id') then v_sql:=v_sql||' or ride_id::text=any($1)'; end if;
    if exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='driver_id') and p_role='driver' then v_sql:=v_sql||' or driver_id::text=any($2)'; end if;
    if exists(select 1 from information_schema.columns where table_schema='public' and table_name='driver_reports' and column_name='passenger_id') and p_role='passenger' then v_sql:=v_sql||' or passenger_id::text=any($2)'; end if;
    execute v_sql using v_ride_ids,v_keys;
  end if;

  -- Cualquier tabla adicional con FK a rides se limpia antes de borrar viajes.
  for v_fk in
    select ns.nspname schema_name,cl.relname table_name,att.attname column_name
    from pg_constraint con join pg_class cl on cl.oid=con.conrelid join pg_namespace ns on ns.oid=cl.relnamespace
    join unnest(con.conkey) ck(attnum) on true join pg_attribute att on att.attrelid=con.conrelid and att.attnum=ck.attnum
    where con.contype='f' and con.confrelid='public.rides'::regclass and con.conrelid<>con.confrelid and array_length(con.conkey,1)=1
  loop
    begin execute format('delete from %I.%I where %I::text=any($1)',v_fk.schema_name,v_fk.table_name,v_fk.column_name) using v_ride_ids; exception when others then null; end;
  end loop;
  delete from public.rides where id::text=any(v_ride_ids);

  begin
    with removed as (
      delete from storage.objects where bucket_id='sobre-ruedas-media' and (
        name like '%/'||coalesce(v_profile.device_id,'__none__')||'/%' or name like '%/'||v_profile.id::text||'/%') returning 1
    ) select count(*) into v_media_count from removed;
  exception when others then v_media_count:=0;
  end;

  -- Cualquier tabla adicional con FK a profiles se limpia con comparación textual compatible.
  for v_fk in
    select ns.nspname schema_name,cl.relname table_name,att.attname column_name
    from pg_constraint con join pg_class cl on cl.oid=con.conrelid join pg_namespace ns on ns.oid=cl.relnamespace
    join unnest(con.conkey) ck(attnum) on true join pg_attribute att on att.attrelid=con.conrelid and att.attnum=ck.attnum
    where con.contype='f' and con.confrelid='public.profiles'::regclass and con.conrelid<>con.confrelid and array_length(con.conkey,1)=1
  loop
    begin execute format('delete from %I.%I where %I::text=any($1)',v_fk.schema_name,v_fk.table_name,v_fk.column_name) using v_keys; exception when others then null; end;
  end loop;
  delete from public.profiles where id=v_profile.id;

  begin
    insert into public.admin_action_log(action,target_id,target_role,reason,admin_name,metadata,created_at)
    values('permanent_delete_'||p_role,'[eliminado]',p_role,trim(p_reason),p_admin_name,
      jsonb_build_object('rides_deleted',v_rides_count,'media_deleted',v_media_count),now());
  exception when others then null;
  end;
  return jsonb_build_object('ok',true,'role',p_role,'rides_deleted',v_rides_count,'media_deleted',v_media_count);
end;
$$;

create or replace function public.admin_resolve_ride_v280(
  p_ride_id text,p_action text,p_reason text,p_admin_name text,p_admin_code text
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_ride public.rides;v_now timestamptz:=now();
begin
  if p_admin_code is distinct from 'RUEDA2026' then raise exception using errcode='P0001',message='ADMIN_CODE_INVALID'; end if;
  if p_action not in ('finish','cancel') then raise exception using errcode='P0001',message='ADMIN_RIDE_ACTION_INVALID'; end if;
  if nullif(trim(coalesce(p_reason,'')),'') is null then raise exception using errcode='P0001',message='ADMIN_RIDE_REASON_REQUIRED'; end if;
  select * into v_ride from public.rides where id::text=p_ride_id for update;
  if not found then raise exception using errcode='P0001',message='RIDE_NOT_FOUND'; end if;
  if p_action='finish' then
    if v_ride.status not in ('accepted','arrived','in_progress') then raise exception using errcode='P0001',message='RIDE_CANNOT_BE_FINISHED_FROM_CURRENT_STATUS'; end if;
    update public.rides set status='finished',finished_at=coalesce(finished_at,v_now),admin_finished_at=v_now,
      admin_finished_by=coalesce(nullif(trim(p_admin_name),''),'administración'),admin_note=trim(p_reason),
      offered_driver_id=null,offered_at=null,offer_expires_at=null,last_event_at=v_now,updated_at=v_now
    where id::text=p_ride_id returning * into v_ride;
  else
    if v_ride.status not in ('searching','accepted','arrived','in_progress') then raise exception using errcode='P0001',message='RIDE_CANNOT_BE_CANCELED_FROM_CURRENT_STATUS'; end if;
    update public.rides set status='canceled',canceled_at=coalesce(canceled_at,v_now),canceled_by='admin',cancel_reason=trim(p_reason),
      admin_note=trim(p_reason),offered_driver_id=null,offered_at=null,offer_expires_at=null,last_event_at=v_now,updated_at=v_now
    where id::text=p_ride_id returning * into v_ride;
  end if;
  begin insert into public.ride_events(ride_id,event_type,actor_role,actor_id,metadata)
    values(p_ride_id,'admin_'||p_action,'admin',p_admin_name,jsonb_build_object('reason',trim(p_reason),'status',v_ride.status));
  exception when others then null; end;
  return jsonb_build_object('ok',true,'ride_id',p_ride_id,'status',v_ride.status);
end;
$$;

create or replace function public.create_support_case_v280(
  p_creator_id text,p_creator_role text,p_ride_id text,p_category text,p_subject text,p_description text,p_priority text default 'normal'
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_case public.support_cases;
begin
  if p_creator_role not in ('passenger','driver') then raise exception using errcode='P0001',message='SUPPORT_ROLE_INVALID'; end if;
  if nullif(trim(coalesce(p_creator_id,'')),'') is null then raise exception using errcode='P0001',message='SUPPORT_CREATOR_REQUIRED'; end if;
  if nullif(trim(coalesce(p_category,'')),'') is null or length(trim(coalesce(p_description,'')))<8 then raise exception using errcode='P0001',message='SUPPORT_DETAILS_REQUIRED'; end if;
  insert into public.support_cases(created_by_id,created_by_role,related_ride_id,category,subject,description,priority,status,created_at,updated_at)
  values(p_creator_id,p_creator_role,nullif(trim(coalesce(p_ride_id,'')),''),trim(p_category),
    coalesce(nullif(trim(coalesce(p_subject,'')),''),trim(p_category)),trim(p_description),
    case when p_priority in ('normal','high','emergency') then p_priority else 'normal' end,'open',now(),now()) returning * into v_case;
  insert into public.support_messages(case_id,sender_id,sender_role,message,created_at)
  values(v_case.id,p_creator_id,p_creator_role,trim(p_description),now());
  if nullif(trim(coalesce(p_ride_id,'')),'') is not null then update public.rides set support_flag=true,updated_at=now() where id::text=p_ride_id; end if;
  return to_jsonb(v_case);
end;
$$;

create or replace function public.submit_ride_rating_v280(
  p_ride_id text,p_passenger_id text,p_rating integer,p_comment text default null
)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_ride public.rides;
begin
  if p_rating<1 or p_rating>5 then raise exception using errcode='P0001',message='RATING_INVALID'; end if;
  select * into v_ride from public.rides r where r.id::text=p_ride_id and r.status='finished'
    and (r.passenger_id::text=p_passenger_id or exists(select 1 from public.profiles p where p.role='passenger' and p.device_id=p_passenger_id and p.id::text=r.passenger_id::text)) for update;
  if not found then raise exception using errcode='P0001',message='RIDE_NOT_FOUND_OR_NOT_RATEABLE'; end if;
  if v_ride.rating is not null then return jsonb_build_object('ok',true,'already_rated',true,'rating',v_ride.rating); end if;
  update public.rides set rating=p_rating,rating_comment=nullif(trim(coalesce(p_comment,'')),''),rated_at=now(),updated_at=now() where id=v_ride.id returning * into v_ride;
  if p_rating<=3 then
    insert into public.driver_reports(ride_id,driver_id,driver_name,passenger_id,passenger_name,rating,passenger_comment,reviewed,risk_level,created_at,updated_at)
    values(v_ride.id::text,v_ride.driver_id,v_ride.driver_name,v_ride.passenger_id,v_ride.passenger_name,p_rating,nullif(trim(coalesce(p_comment,'')),''),false,'green',now(),now())
    on conflict(ride_id) where ride_id is not null do update set rating=excluded.rating,passenger_comment=excluded.passenger_comment,updated_at=now();
  end if;
  return jsonb_build_object('ok',true,'rating',p_rating);
end;
$$;

create or replace function public.driver_earnings_summary_v280(p_driver_id text)
returns jsonb language sql security definer set search_path=public as $$
  with keys as (
    select p_driver_id key
    union
    select p.id::text from public.profiles p where p.role='driver' and (p.device_id=p_driver_id or p.id::text=p_driver_id)
    union
    select p.device_id from public.profiles p where p.role='driver' and (p.device_id=p_driver_id or p.id::text=p_driver_id)
  ),base as (
    select coalesce(r.price,0)::numeric amount,coalesce(r.finished_at,r.updated_at,r.created_at) completed_at
    from public.rides r where r.driver_id::text in (select key from keys where key is not null) and r.status='finished'
  ),bounds as (
    select (date_trunc('day',now() at time zone 'America/Havana') at time zone 'America/Havana') day_start,
      (date_trunc('week',now() at time zone 'America/Havana') at time zone 'America/Havana') week_start,
      (date_trunc('month',now() at time zone 'America/Havana') at time zone 'America/Havana') month_start
  )
  select jsonb_build_object('today',coalesce(sum(amount) filter(where completed_at>=day_start),0),
    'week',coalesce(sum(amount) filter(where completed_at>=week_start),0),
    'month',coalesce(sum(amount) filter(where completed_at>=month_start),0),
    'trips_today',count(*) filter(where completed_at>=day_start)) from base cross join bounds
$$;

