-- Impide que un conductor suspendido, desaprobado o eliminado acepte/continúe viajes.
create or replace function public.enforce_ride_driver_operability_v280()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_ok boolean;
begin
  if new.offered_driver_id is not null and new.status='searching' then
    select exists(select 1 from public.profiles p where p.role='driver'
      and (p.device_id=new.offered_driver_id or p.id::text=new.offered_driver_id)
      and p.status='active' and p.approval_status='approved'
      and (p.suspended_until is null or p.suspended_until<=now())
      and coalesce(p.is_online,false)=true) into v_ok;
    if not coalesce(v_ok,false) then
      new.offered_driver_id:=null;new.offered_at:=null;new.offer_expires_at:=null;
    end if;
  end if;
  if new.driver_id is not null and new.status in ('accepted','arrived','in_progress') then
    select exists(select 1 from public.profiles p where p.role='driver'
      and (p.device_id=new.driver_id or p.id::text=new.driver_id)
      and p.status='active' and p.approval_status='approved'
      and (p.suspended_until is null or p.suspended_until<=now())) into v_ok;
    if not coalesce(v_ok,false) then
      raise exception using errcode='P0001',message='DRIVER_NOT_OPERABLE';
    end if;
  end if;
  return new;
end;
$$;
drop trigger if exists rides_enforce_driver_operability_v280 on public.rides;
create trigger rides_enforce_driver_operability_v280
before insert or update of status,driver_id,offered_driver_id on public.rides
for each row execute function public.enforce_ride_driver_operability_v280();


