create or replace function public.sr_hash_contact_v280(p_value text)
returns text language sql immutable strict as $$
  select encode(digest(lower(regexp_replace(trim(p_value),'\s+','','g')),'sha256'),'hex')
$$;

create or replace function public.is_deleted_account_v280(
  p_device_id text,p_role text,p_email text default null,p_phone text default null
)
returns boolean language sql security definer set search_path=public as $$
  select exists(
    select 1 from public.deleted_accounts d
    where d.role=p_role and (
      d.device_id=p_device_id
      or (nullif(trim(coalesce(p_email,'')),'') is not null and d.email_hash=public.sr_hash_contact_v280(p_email))
      or (nullif(trim(coalesce(p_phone,'')),'') is not null and d.phone_hash=public.sr_hash_contact_v280(p_phone))
    )
  )
$$;

create or replace function public.prevent_deleted_account_recreation_v280()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if public.is_deleted_account_v280(new.device_id,new.role,new.email,new.phone) then
    raise exception using errcode='P0001',message='ACCOUNT_PERMANENTLY_DELETED';
  end if;
  return new;
end;
$$;
