on conflict(vehicle_type) do nothing;

create table if not exists public.ride_events (
  id bigint generated by default as identity primary key,
  ride_id uuid references public.rides(id) on delete cascade,
  event_type text not null, actor_role text, actor_id text,
  metadata jsonb default '{}'::jsonb, created_at timestamptz default now()
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  ride_id uuid references public.rides(id) on delete set null,
  reporter_id text, reporter_role text, category text, description text,
  status text default 'open', assigned_admin uuid references public.admin_users(id),
  resolution_notes text, created_at timestamptz default now(), resolved_at timestamptz
);

