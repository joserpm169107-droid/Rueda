-- Ejecutar en Supabase > SQL Editor.

create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(), device_id text unique,
  role text not null check (role in ('passenger','driver','admin','owner')),
  full_name text, phone text, email text, photo_url text, status text default 'active',
  vehicle_type text, vehicle_plate text, rating numeric default 5,
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.admin_users (
  id uuid primary key default gen_random_uuid(), profile_id uuid references public.profiles(id) on delete cascade,
  admin_role text not null default 'supervisor' check (admin_role in ('owner','supervisor','support','driver_reviewer','accounting')),
  active boolean default true, created_at timestamptz default now()
);

create table if not exists public.fare_settings (
  vehicle_type text primary key, base_fare numeric not null default 0,
  per_km numeric not null default 0, minimum_fare numeric not null default 0,
  active boolean default true, updated_at timestamptz default now()
);

insert into public.fare_settings(vehicle_type,base_fare,per_km,minimum_fare) values
